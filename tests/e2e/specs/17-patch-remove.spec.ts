interface Ask {
  field: string;
  kind: string;
  suggestion?: number;
}

interface Scan {
  candidates: Array<{ defName: string; status: string; asks: Ask[] }>;
}

const PATCH = join('Compat', 'CombatExtended', 'Patches', 'gewehr41_Weapons_Ranged.xml');

/** The answers a person gives on the questions tab: the two choices, the two flags and every estimate. */
function answersOf(asks: Ask[]): object {
  const sourced = (value: number | undefined) => ({ value, source: 'answered' });
  const overrides: Record<string, unknown> = { oneHanded: false, beltFed: false };
  const tools = new Map<string, Record<string, unknown>>();
  const answers: Record<string, unknown> = { overrides };
  for (const ask of asks) {
    const [, , name = '', tool = '', side = ''] = ask.field.split('/');
    if (ask.field === '/ce/ammoSet') answers.ammoSet = 'AmmoSet_303British';
    else if (ask.field === '/ce/weaponTagClass') answers.weaponTagClass = 'CE_AI_SR';
    else if (ask.field === '/ce/oneHanded') answers.oneHanded = false;
    else if (ask.field === '/ce/beltFed') answers.beltFed = false;
    else if (ask.kind !== 'number') continue;
    else if (name === 'toolPenetration') {
      const entry = tools.get(tool) ?? { tool };
      entry[side] = sourced(ask.suggestion);
      tools.set(tool, entry);
    } else overrides[name] = sourced(ask.suggestion);
  }
  if (tools.size > 0) answers.toolPenetration = [...tools.values()];
  return answers;
}

/** Converts weapons through the bridge, as the page does, so the mod holds patches generated by RimStudio. */
async function convert(env: E2eEnv, mod: string, defNames: string[]): Promise<void> {
  const { projectId } = await rpc<{ projectId: string }>(env, 'project_open', { path: mod });
  for (const defName of defNames) {
    const scan = await rpc<Scan>(env, 'designer_convert_scan', { projectId, includeConverted: true });
    const asks = scan.candidates.find((c) => c.defName === defName)?.asks ?? [];
    const request = {
      projectId,
      draft: {
        schemaVersion: 1,
        kind: 'ranged',
        calibration: 'simple',
        spec: {
          kind: 'ranged',
          identity: { defName, label: '', description: '', modPrefix: '' },
          previewQuality: 'normal',
          ranged: { accuracy: {}, verbClass: 'Verb_Shoot' },
        },
      },
      convert: { defName, answers: answersOf(asks) },
    };
    const plan = await rpc<{ planId: string; hasErrors: boolean; diagnostics: Array<{ message: string }> }>(
      env,
      'designer_export_plan',
      request,
    );
    expect(plan.hasErrors, `plan of ${defName}: ${plan.diagnostics.map((d) => d.message).join('; ')}`).toBe(false);
    await rpc(env, 'designer_apply_plan', {
      planId: plan.planId,
      request,
      backup: false,
      dryApply: false,
    });
  }
}

test.describe.configure({ mode: 'serial' });

test.describe('patches: remove or replace the patch RimStudio generated', () => {
  test('remove one weapon of a shared file, then replace the last one and generate it again', async ({
    page,
    env,
    shot,
  }) => {
    const work = join(env.tmp, 'work-remove');
    mkdirSync(work, { recursive: true });
    const mod = copyGewehr(work);
    await convert(env, mod, ['OH_G41m', 'OH_G41w']);
    expect(readFileSync(join(mod, PATCH), 'utf8')).toContain('====== OH_G41w ======');
    const definitions = readFileSync(
      join(mod, 'Defs', 'ThingDefs_Misc', 'Weapons', 'RangedIndustrial.xml'),
      'utf8',
    );

    await rememberProject(page, mod);
    await gotoRoute(page, env, '/patches');
    const table = page.getByRole('grid', { name: 'Weapons of the mod' });
    await expect(page.getByText('2 already CE')).toBeVisible({ timeout: 60_000 });

    // the first weapon: its patch was generated, so the card offers both choices
    await table.getByText('OH_G41m', { exact: true }).click();
    const card = page.getByRole('region', { name: 'Existing conversion' });
    await expect(card.getByText('Generated by RimStudio.')).toBeVisible();
    await expect(card.getByText('Compat/CombatExtended/Patches/gewehr41_Weapons_Ranged.xml').first()).toBeVisible();
    await shot('patch-removal-card');
    expect(describe(await axeViolations(page)), 'axe card').toBe('');

    // remove: the section of this weapon is cut out of the file that two weapons share
    await card.getByRole('button', { name: 'Remove patch' }).click();
    const dialog = page.getByRole('dialog', { name: 'Remove the patch of Gewehr 41 (m)' });
    await expect(dialog.getByText('Section of this weapon removed')).toBeVisible({ timeout: 30_000 });
    await expect(dialog.getByRole('region', { name: /^Changes to / })).toContainText('====== OH_G41m ======');
    await shot('patch-removal-review');
    expect(describe(await axeViolations(page)), 'axe review').toBe('');
    expect(readFileSync(join(mod, PATCH), 'utf8')).toContain('====== OH_G41m ======');
    await dialog.getByRole('button', { name: 'Remove patch' }).click();
    await expect(dialog.getByText('Patch removed')).toBeVisible({ timeout: 60_000 });
    await expect(dialog.getByText('Backup:')).toBeVisible();
    await shot('patch-removal-done');
    expect(describe(await axeViolations(page)), 'axe done').toBe('');
    await dialog.getByRole('button', { name: 'Close' }).last().click();

    const afterFirst = readFileSync(join(mod, PATCH), 'utf8');
    expect(afterFirst).not.toContain('====== OH_G41m ======');
    expect(afterFirst).toContain('====== OH_G41w ======');
    // the page looked at the mod again and the weapon is not converted any more
    await expect(page.getByText('1 already CE')).toBeVisible({ timeout: 60_000 });
    await expect(page.getByText('4 not converted')).toBeVisible();

    // replace: the file holds nothing else, so it goes, and the weapon opens on its questions
    await table.getByText('OH_G41w', { exact: true }).click();
    await page
      .getByRole('region', { name: 'Existing conversion' })
      .getByRole('button', { name: 'Replace patch' })
      .click();
    const replace = page.getByRole('dialog', { name: 'Replace the patch of Gewehr 41 (w)' });
    await expect(replace.getByText('File deleted because nothing else is in it')).toBeVisible({
      timeout: 30_000,
    });
    await expect(replace.getByText(/questions are asked again/)).toBeVisible();
    await shot('patch-removal-replace');
    await replace.getByRole('button', { name: 'Remove and generate again' }).click();
    await expect(replace.getByText('Patch removed')).toBeVisible({ timeout: 60_000 });
    await replace.getByRole('button', { name: 'Close' }).last().click();
    expect(existsSync(join(mod, PATCH))).toBe(false);

    // the same weapon is still selected, shown with its questions
    await expect(page.getByRole('heading', { name: 'Gewehr 41 (w)' })).toBeVisible();
    await expect(page.getByRole('tab', { name: /^Questions/ })).toHaveAttribute('aria-selected', 'true', {
      timeout: 60_000,
    });
    await expect(page.getByRole('region', { name: 'Existing conversion' })).toHaveCount(0);
    await shot('patch-removal-questions');

    // the definitions of the weapons were never touched
    expect(
      readFileSync(join(mod, 'Defs', 'ThingDefs_Misc', 'Weapons', 'RangedIndustrial.xml'), 'utf8'),
    ).toBe(definitions);
  });
  test('a conversion written by hand is described and never offered for removal', async ({
    page,
    env,
    shot,
  }) => {
    const mod = copyGewehrWithPatch(join(env.tmp, 'work-by-hand'));
    const before = readFileSync(join(mod, 'Patches', 'ce_patch.xml'), 'utf8');

    await rememberProject(page, mod);
    await gotoRoute(page, env, '/patches');
    await expect(page.getByText(/[0-9]+ already CE/)).toBeVisible({ timeout: 60_000 });
    const card = page.getByRole('region', { name: 'Existing conversion' });
    await expect(card.getByText('Written by hand in this mod.')).toBeVisible();
    await expect(card.getByText('Patches/ce_patch.xml')).toBeVisible();
    await expect(card.getByText(/never changed here/)).toBeVisible();
    await expect(card.getByRole('button')).toHaveCount(0);
    await shot('patch-removal-by-hand');
    expect(describe(await axeViolations(page)), 'axe by hand').toBe('');
    expect(readFileSync(join(mod, 'Patches', 'ce_patch.xml'), 'utf8')).toBe(before);
  });
});

import { signal } from '@preact/signals';
import type {
  ApiError,
  ApplyReportDto,
  ConvertCandidateDto,
  ItemKindDto,
  WritePlanDto,
} from 'rimstudio-ipc-types';
import { normalizeError } from '~/shared/ipc';
import { bumpProjectRevision, type ProjectRef } from '~/shared/project';
import { applyRemoval, planRemoval } from './api';
import { resetPlans } from './planStore';
import { withOpenProject } from './session';

/**
 * What the person asked for: take the generated patch out, or take it out so that a new one can be
 * generated. Both write the same files; the mode only changes the words and what the page does next.
 */
export type RemovalMode = 'remove' | 'replace';

/** The weapon a removal is about. */
export interface RemovalTarget {
  defName: string;
  /** What the dialog calls the weapon: its label, or the definition name when it has none. */
  name: string;
  kind: ItemKindDto;
  mode: RemovalMode;
  /**
   * True when the conversion itself was not generated by RimStudio (a patch written by hand, or one of
   * another mod, with sections RimStudio generated on top): only those sections go and the weapon stays
   * converted.
   */
  keepsConversion: boolean;
}

export type RemovalState =
  | { phase: 'closed' }
  | { phase: 'planning'; target: RemovalTarget }
  | { phase: 'review'; target: RemovalTarget; plan: WritePlanDto }
  | { phase: 'running'; target: RemovalTarget; plan: WritePlanDto }
  | { phase: 'done'; target: RemovalTarget; plan: WritePlanDto; report: ApplyReportDto }
  | { phase: 'failed'; target: RemovalTarget; error: ApiError };

export const removal = signal<RemovalState>({ phase: 'closed' });

/** Counts up with every open, close and confirm, so an answer that arrives late is dropped. */
let sequence = 0;

/** The target of a weapon of the scan. */
export function removalTarget(candidate: ConvertCandidateDto, mode: RemovalMode): RemovalTarget {
  return {
    defName: candidate.defName,
    name: candidate.label || candidate.defName,
    kind: candidate.kind ?? 'ranged',
    mode,
    keepsConversion: candidate.existing !== undefined && candidate.existing.origin !== 'rimstudio',
  };
}

/** Whether a plan can be applied: it has files and no error diagnostic. */
export function isRemovable(plan: WritePlanDto): boolean {
  return !plan.hasErrors && plan.files.length > 0;
}

/** Plan the removal of the generated patch of one weapon and open the review. */
export async function openRemoval(project: ProjectRef, target: RemovalTarget): Promise<void> {
  const mine = ++sequence;
  removal.value = { phase: 'planning', target };
  try {
    const plan = await withOpenProject(project, (id) =>
      planRemoval(id, target.kind, target.defName),
    );
    if (mine !== sequence) return;
    removal.value = { phase: 'review', target, plan };
  } catch (thrown) {
    if (mine !== sequence) return;
    removal.value = { phase: 'failed', target, error: normalizeError(thrown) };
  }
}

/**
 * Apply the reviewed plan. The files are changed on disk whatever happens to the dialog, so the plans are
 * dropped and the page is told to rescan even when the dialog was closed meanwhile.
 */
export async function confirmRemoval(project: ProjectRef): Promise<void> {
  const state = removal.peek();
  // a second click, or a plan with errors, must not start a write
  if (state.phase !== 'review' || !isRemovable(state.plan)) return;
  const { target, plan } = state;
  const mine = ++sequence;
  removal.value = { phase: 'running', target, plan };
  try {
    const report = await withOpenProject(project, (id) =>
      applyRemoval(plan.planId, id, target.kind, target.defName),
    );
    resetPlans();
    // the page rescans when the revision changes
    bumpProjectRevision();
    if (mine === sequence) removal.value = { phase: 'done', target, plan, report };
  } catch (thrown) {
    // a failed write can have changed some of the files, so the page looks at the disk again
    resetPlans();
    bumpProjectRevision();
    if (mine === sequence) {
      removal.value = { phase: 'failed', target, error: normalizeError(thrown) };
    }
  }
}

/** Close the dialog; an answer that is still on its way is dropped. */
export function closeRemoval(): void {
  sequence += 1;
  removal.value = { phase: 'closed' };
}

/** Back to the closed state (tests and project changes). */
export function resetRemoval(): void {
  closeRemoval();
}

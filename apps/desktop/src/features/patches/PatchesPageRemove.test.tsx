import { fireEvent, screen, waitFor, within } from '@testing-library/preact';
import { loadFixture, renderWithProviders } from 'rimstudio-testkit';
import type { ConvertCandidateDto, ConvertScanDto } from 'rimstudio-ipc-types';
import { beforeEach, describe, expect, it } from 'vitest';
import { focused } from './scanStore';
import PatchesPage from './PatchesPage';
import { installTransport, openFixtureProject } from './testSupport';

beforeEach(() => {
  window.location.hash = '#/patches';
});

const converted = loadFixture<ConvertScanDto>('patches-scan-converted');
const plain = loadFixture<ConvertScanDto>('designer_convert_scan');

/** The scan of the converted mod, with the given weapons shown as the scan sees them after a removal. */
function scanWithout(...removed: string[]): ConvertScanDto {
  const fresh = (c: ConvertCandidateDto): ConvertCandidateDto =>
    plain.candidates.find((p) => p.defName === c.defName) ?? c;
  const candidates = converted.candidates.map((c) => (removed.includes(c.defName) ? fresh(c) : c));
  const already = candidates.filter((c) => c.status === 'already-ce').length;
  return {
    ...converted,
    candidates,
    counts: { ...converted.counts, alreadyCe: already, notConverted: candidates.length - already },
  };
}

/** A mod whose weapon OH_G41m has its generated patch removed by the first apply. */
function renderConvertedMod() {
  let removed = false;
  const transport = installTransport({
    designer_convert_scan: () => scanWithout(...(removed ? ['OH_G41m'] : [])),
    designer_apply_plan: () => {
      removed = true;
      return loadFixture('patches-apply-remove');
    },
  });
  openFixtureProject('patches-project-converted');
  renderWithProviders(<PatchesPage />);
  return transport;
}

describe('PatchesPage removal of a generated patch', () => {
  it('shows the existing conversion of the focused weapon', async () => {
    renderConvertedMod();
    await screen.findByRole('grid', { name: 'Weapons of the mod' });
    const card = await screen.findByRole('region', { name: 'Existing conversion' });
    expect(within(card).getByText('Generated by RimStudio.')).toBeTruthy();
    expect(within(card).getByRole('button', { name: 'Remove patch' })).toBeTruthy();
    expect(within(card).getByRole('button', { name: 'Replace patch' })).toBeTruthy();
  });

  it('removes the patch after a review of the diff and rescans the mod', async () => {
    const transport = renderConvertedMod();
    await screen.findByRole('grid', { name: 'Weapons of the mod' });
    fireEvent.click(await screen.findByRole('button', { name: 'Remove patch' }));
    const dialog = await screen.findByRole('dialog', { name: 'Remove the patch of Gewehr 41 (m)' });
    expect(await within(dialog).findByText('Section of this weapon removed')).toBeTruthy();
    const scans = transport.calls.filter((c) => c.name === 'designer_convert_scan').length;
    fireEvent.click(within(dialog).getByRole('button', { name: 'Remove patch' }));
    expect(await within(dialog).findByText('Patch removed')).toBeTruthy();
    const applied = transport.calls.find((c) => c.name === 'designer_apply_plan')?.request;
    expect(applied).toMatchObject({ request: { convert: { defName: 'OH_G41m', remove: true } } });
    // the page looks at the mod again: the weapon is not converted any more
    await waitFor(() =>
      expect(transport.calls.filter((c) => c.name === 'designer_convert_scan').length).toBe(
        scans + 1,
      ),
    );
    const table = await screen.findByRole('grid', { name: 'Weapons of the mod' });
    await waitFor(() => expect(within(table).getAllByText('Not converted')).toHaveLength(1));
    expect(within(table).getAllByText('Already CE')).toHaveLength(4);
    fireEvent.click(within(dialog).getAllByRole('button', { name: 'Close' }).at(-1) as HTMLElement);
    await waitFor(() => expect(screen.queryByRole('dialog')).toBeNull());
    expect(screen.queryByRole('region', { name: 'Existing conversion' })).toBeNull();
  });

  it('keeps the weapon selected after a replace and opens it on its questions', async () => {
    renderConvertedMod();
    await screen.findByRole('grid', { name: 'Weapons of the mod' });
    expect(focused.value).toBe('OH_G41m');
    expect(screen.getByRole('tab', { name: 'Plan' }).getAttribute('aria-selected')).toBe('true');
    fireEvent.click(await screen.findByRole('button', { name: 'Replace patch' }));
    const dialog = await screen.findByRole('dialog', {
      name: 'Replace the patch of Gewehr 41 (m)',
    });
    fireEvent.click(
      await within(dialog).findByRole('button', { name: 'Remove and generate again' }),
    );
    expect(await within(dialog).findByText('Patch removed')).toBeTruthy();
    fireEvent.click(within(dialog).getAllByRole('button', { name: 'Close' }).at(-1) as HTMLElement);
    await waitFor(() => expect(screen.queryByRole('dialog')).toBeNull());
    // the same weapon, now with its questions
    await waitFor(() =>
      expect(screen.getByRole('tab', { name: /Questions/ }).getAttribute('aria-selected')).toBe(
        'true',
      ),
    );
    expect(focused.value).toBe('OH_G41m');
    expect(screen.getByRole('heading', { name: 'Gewehr 41 (m)' })).toBeTruthy();
    expect(screen.getByText('0 of 9 answered')).toBeTruthy();
    expect(screen.queryByRole('region', { name: 'Existing conversion' })).toBeNull();
  });

  it('plans the weapon again after a removal that left it converted', async () => {
    // another conversion of the weapon remains, so the scan still lists it as already converted
    const transport = installTransport({
      // every scan answers with new objects, as a real one does
      designer_convert_scan: () => structuredClone(converted),
      designer_apply_plan: () => loadFixture('patches-apply-remove'),
    });
    openFixtureProject('patches-project-converted');
    renderWithProviders(<PatchesPage />);
    await screen.findByRole('grid', { name: 'Weapons of the mod' });
    await waitFor(() =>
      expect(transport.calls.filter((c) => c.name === 'designer_export_plan')).toHaveLength(1),
    );
    fireEvent.click(await screen.findByRole('button', { name: 'Remove patch' }));
    const dialog = await screen.findByRole('dialog');
    fireEvent.click(await within(dialog).findByRole('button', { name: 'Remove patch' }));
    expect(await within(dialog).findByText('Patch removed')).toBeTruthy();
    const plans = (): number =>
      transport.calls.filter(
        (c) =>
          c.name === 'designer_export_plan' &&
          !(c.request as { convert?: { remove?: boolean } }).convert?.remove,
      ).length;
    // the plan of the update mode was dropped with the run and asked for again after the rescan
    await waitFor(() => expect(plans()).toBe(2));
  });

  it('offers no removal for a conversion written by hand', async () => {
    renderConvertedMod();
    const table = await screen.findByRole('grid', { name: 'Weapons of the mod' });
    fireEvent.click(within(table).getByText('OH_G41w_sniper'));
    const card = await screen.findByRole('region', { name: 'Existing conversion' });
    expect(within(card).getByText('Written by hand in this mod.')).toBeTruthy();
    expect(within(card).getByText('Patches/ce_patch.xml')).toBeTruthy();
    expect(within(card).queryByRole('button')).toBeNull();
  });
});

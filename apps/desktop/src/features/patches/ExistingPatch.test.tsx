import { fireEvent, render, screen, within } from '@testing-library/preact';
import type { ExistingPatchDto } from 'rimstudio-ipc-types';
import { describe, expect, it, vi } from 'vitest';
import { ExistingPatch } from './ExistingPatch';

const GENERATED = 'Compat/CombatExtended/Patches/gewehr41_Weapons_Ranged.xml';

const generated: ExistingPatchDto = {
  origin: 'rimstudio',
  file: GENERATED,
  files: [GENERATED],
  removable: true,
};

function renderCard(existing: ExistingPatchDto, handlers = { remove: vi.fn(), replace: vi.fn() }) {
  render(
    <ExistingPatch existing={existing} onRemove={handlers.remove} onReplace={handlers.replace} />,
  );
  return handlers;
}

describe('ExistingPatch', () => {
  it('says the patch was generated, names its files and offers to remove or replace it', () => {
    const handlers = renderCard(generated);
    const card = screen.getByRole('region', { name: 'Existing conversion' });
    expect(within(card).getByText('Generated by RimStudio.')).toBeTruthy();
    expect(within(card).getByLabelText('Where the conversion is').tagName).toBe('DL');
    expect(within(card).getByText('File that a removal changes')).toBeTruthy();
    // the file that holds the conversion is the file a removal changes: it is named once
    expect(within(card).getAllByText(GENERATED)).toHaveLength(1);
    expect(within(card).queryByText('Conversion file')).toBeNull();
    fireEvent.click(within(card).getByRole('button', { name: 'Remove patch' }));
    expect(handlers.remove).toHaveBeenCalledTimes(1);
    expect(handlers.replace).not.toHaveBeenCalled();
    fireEvent.click(within(card).getByRole('button', { name: 'Replace patch' }));
    expect(handlers.replace).toHaveBeenCalledTimes(1);
    expect(screen.queryByText(/never changed here/)).toBeNull();
  });

  it('names the file of the conversion when the removal changes other files', () => {
    renderCard({ ...generated, file: 'Patches/ce_patch.xml' });
    expect(screen.getByText('Conversion file')).toBeTruthy();
    expect(screen.getByText('Patches/ce_patch.xml')).toBeTruthy();
    expect(screen.getByText('File that a removal changes')).toBeTruthy();
    expect(screen.getByText(GENERATED)).toBeTruthy();
  });

  it('lists every generated file that a removal changes', () => {
    renderCard({
      ...generated,
      files: [GENERATED, 'Compat/CombatExtended/Patches/gewehr41_Weapons_Melee.xml'],
    });
    expect(screen.getByText('Files that a removal changes')).toBeTruthy();
    expect(
      screen.getByText('Compat/CombatExtended/Patches/gewehr41_Weapons_Melee.xml'),
    ).toBeTruthy();
  });

  it("offers only the removal when the sections are overrides on a conversion that is not RimStudio's", () => {
    const handlers = renderCard({
      origin: 'project',
      file: 'Patches/ce_patch.xml',
      files: ['Compat/CombatExtended/Patches/Weapons_Ranged_Update.xml'],
      removable: true,
    });
    expect(screen.getByText('Written by hand in this mod.')).toBeTruthy();
    expect(screen.getByText('Patches/ce_patch.xml')).toBeTruthy();
    expect(
      screen.getByText('Compat/CombatExtended/Patches/Weapons_Ranged_Update.xml'),
    ).toBeTruthy();
    expect(screen.getByText(/The conversion itself stays/)).toBeTruthy();
    // after the removal the weapon is still converted by the hand written patch, so nothing is replaced
    expect(screen.queryByRole('button', { name: 'Replace patch' })).toBeNull();
    fireEvent.click(screen.getByRole('button', { name: 'Remove patch' }));
    expect(handlers.remove).toHaveBeenCalledTimes(1);
  });

  it('explains a patch written by hand and offers no button', () => {
    renderCard({ origin: 'project', file: 'Patches/ce_patch.xml', removable: false });
    expect(screen.getByText('Written by hand in this mod.')).toBeTruthy();
    expect(screen.getByText('Patches/ce_patch.xml')).toBeTruthy();
    expect(screen.getByText(/never changed here/)).toBeTruthy();
    expect(screen.getByText(/Update mode still works/)).toBeTruthy();
    expect(screen.queryByRole('button')).toBeNull();
    expect(screen.queryByText('File that a removal changes')).toBeNull();
  });

  it('names the mod that converted the weapon and never offers to change it', () => {
    renderCard({ origin: 'foreign', modName: 'Armory Plus', removable: false });
    expect(
      screen.getByText('Converted by the mod Armory Plus; RimStudio never edits other mods.'),
    ).toBeTruthy();
    expect(screen.queryByText('Conversion file')).toBeNull();
    expect(screen.queryByRole('button')).toBeNull();
  });

  it('still speaks of another mod when its name is not known', () => {
    renderCard({ origin: 'foreign', removable: false });
    expect(
      screen.getByText('Converted by another mod; RimStudio never edits other mods.'),
    ).toBeTruthy();
  });

  it('says a conversion that could not be traced is not changed either', () => {
    renderCard({ origin: 'unknown', removable: false });
    expect(screen.getByText('Converted by a patch that could not be traced.')).toBeTruthy();
    expect(screen.queryByRole('button')).toBeNull();
  });
});

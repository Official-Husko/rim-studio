import { hasFixture, loadFixture } from './fixtures';

// Answers of the fixture backed mock that depend on a flag of the request. A recorded fixture is the
// answer to one request; a command with a flag that changes the answer has one fixture per case, and this
// module says which one a request gets.

type Json = Record<string, unknown>;

function record(value: unknown): Json | undefined {
  return typeof value === 'object' && value !== null ? (value as Json) : undefined;
}

/** The definition name of a removal request (`convert.remove` set), or undefined for any other request. */
function removalOf(exportRequest: unknown): string | undefined {
  const convert = record(record(exportRequest)?.convert);
  return convert?.remove === true && typeof convert.defName === 'string'
    ? convert.defName
    : undefined;
}

/** The generated files of a weapon as the scan of a converted mod reports them. */
function generatedFilesOf(defName: string): string[] {
  if (!hasFixture('patches-scan-converted')) return [];
  const scan = loadFixture<{
    candidates?: Array<{ defName?: string; existing?: { files?: string[] } }>;
  }>('patches-scan-converted');
  return scan.candidates?.find((c) => c.defName === defName)?.existing?.files ?? [];
}

/**
 * The plan of a removal: a section of the weapon cut out of its patch file when the scan of the converted
 * mod says generated files hold it, else the error a real removal gives when it finds nothing.
 */
function removalPlan(defName: string): unknown {
  if (generatedFilesOf(defName).length > 0) return loadFixture('patches-plan-remove');
  return {
    planId: '00000000000000000000000000000000',
    files: [],
    diagnostics: [
      {
        code: 'designer.remove-nothing',
        severity: 'error',
        message: `no patch file generated by RimStudio holds a section of ${defName}; there is nothing to remove`,
        field: '/convert/defName',
      },
    ],
    hasErrors: true,
  };
}

/**
 * The answer a request gets when its recorded fixture depends on a flag of the request: the removal of a
 * generated patch (`convert.remove`) for `designer_export_plan` and `designer_apply_plan`. Returns
 * undefined when the command has no variant for this request, so the plain fixture applies.
 */
export function variantAnswer(command: string, request: unknown): { value: unknown } | undefined {
  if (command === 'designer_export_plan') {
    const defName = removalOf(request);
    return defName === undefined ? undefined : { value: removalPlan(defName) };
  }
  if (command === 'designer_apply_plan') {
    // the apply request carries the export request it was planned from
    return removalOf(record(request)?.request) === undefined
      ? undefined
      : { value: loadFixture('patches-apply-remove') };
  }
  return undefined;
}
